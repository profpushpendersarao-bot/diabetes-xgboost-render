def calculate_metrics(
    model,
    X_eval,
    y_eval
):

    predictions = model.predict(X_eval)

    probabilities = model.predict_proba(
        X_eval
    )

    result = {}

    # ------------------------------------------------------------
    # Standard metrics
    # ------------------------------------------------------------

    result["Accuracy"] = accuracy_score(
        y_eval,
        predictions
    )

    result["Balanced_Accuracy"] = balanced_accuracy_score(
        y_eval,
        predictions
    )

    result["Macro_Precision"] = precision_score(
        y_eval,
        predictions,
        average="macro",
        zero_division=0
    )

    result["Macro_Recall"] = recall_score(
        y_eval,
        predictions,
        average="macro",
        zero_division=0
    )

    result["Macro_F1"] = f1_score(
        y_eval,
        predictions,
        average="macro",
        zero_division=0
    )

    result["Weighted_F1"] = f1_score(
        y_eval,
        predictions,
        average="weighted",
        zero_division=0
    )

    result["MCC"] = matthews_corrcoef(
        y_eval,
        predictions
    )

    # ------------------------------------------------------------
    # Multiclass ROC-AUC
    # ------------------------------------------------------------

    y_bin = label_binarize(
        y_eval,
        classes=[0, 1, 2]
    )

    result["ROC_AUC_Macro"] = roc_auc_score(
        y_bin,
        probabilities,
        average="macro",
        multi_class="ovr"
    )

    result["ROC_AUC_Weighted"] = roc_auc_score(
        y_bin,
        probabilities,
        average="weighted",
        multi_class="ovr"
    )

    # ------------------------------------------------------------
    # PR-AUC
    # ------------------------------------------------------------

    pr_auc_values = []

    for class_id in range(3):

        precision, recall, _ = precision_recall_curve(
            y_bin[:, class_id],
            probabilities[:, class_id]
        )

        pr_auc = auc(
            recall,
            precision
        )

        pr_auc_values.append(
            pr_auc
        )

        result[
            f"PR_AUC_{reverse_target_mapping[class_id]}"
        ] = pr_auc

    result["PR_AUC_Macro"] = np.mean(
        pr_auc_values
    )

    # ------------------------------------------------------------
    # Per-class sensitivity and specificity
    # ------------------------------------------------------------

    for class_id in range(3):

        class_name = reverse_target_mapping[
            class_id
        ]

        sensitivity = recall_score(
            y_eval,
            predictions,
            labels=[class_id],
            average="macro",
            zero_division=0
        )

        specificity = calculate_specificity(
            y_eval,
            predictions,
            class_id
        )

        result[
            f"{class_name}_Sensitivity"
        ] = sensitivity

        result[
            f"{class_name}_Specificity"
        ] = specificity

    return result, predictions, probabilities


