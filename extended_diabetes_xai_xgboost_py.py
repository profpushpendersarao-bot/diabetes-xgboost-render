# ================================================================

def calculate_specificity(
    y_true,
    y_pred,
    class_id
):

    cm = confusion_matrix(
        y_true,
        y_pred,
        labels=[0, 1, 2]
    )

    tp = cm[class_id, class_id]

    fn = cm[class_id, :].sum() - tp

    fp = cm[:, class_id].sum() - tp

    tn = cm.sum() - (
        tp + fn + fp
    )

    if (tn + fp) == 0:
        return np.nan

    return tn / (tn + fp)


