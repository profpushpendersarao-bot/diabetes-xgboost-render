def bootstrap_ci(
    y_true,
    y_pred,
    metric_function,
    n_bootstrap=2000,
    confidence=0.95
):

    rng = np.random.default_rng(
        SEED
    )

    scores = []

    y_true = np.asarray(
        y_true
    )

    y_pred = np.asarray(
        y_pred
    )

    n = len(y_true)

    for _ in range(
        n_bootstrap
    ):

        indices = rng.integers(
            0,
            n,
            n
        )

        score = metric_function(
            y_true[indices],
            y_pred[indices]
        )

        scores.append(
            score
        )

    lower = np.percentile(
        scores,
        (1 - confidence) / 2 * 100
    )

    upper = np.percentile(
        scores,
        (1 + confidence) / 2 * 100
    )

    return (
        np.mean(scores),
        lower,
        upper
    )


